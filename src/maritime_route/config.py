@dataclass(frozen=True)
class RoutingConfig:
    """Default parameters of the grid based route planner. 航线规划默认参数。

    Used by :mod:`maritime_route.routing.cost_map`, ``astar``, ``dijkstra`` and
    ``planner``.

    Attributes
    ----------
    grid_resolution_deg:
        Side of one lattice cell, degrees (0.25 deg is about 28 km of latitude).
    max_grid_cells:
        Cell budget of one cost map. If the bounding box needs more cells, the
        resolution is coarsened by a factor 1.5 until it fits (the network has
        to classify every cell, so this bounds the classification time).
    margin_deg:
        Margin added around the bounding box of the waypoints, degrees, so the
        route can bend around a headland that lies outside the direct box.
    diagonal_moves:
        ``True`` - 8-connected lattice (N, S, E, W and diagonals); ``False`` -
        4-connected.
    heuristic_weight:
        Multiplier of the A* great-circle heuristic. 1.0 keeps the heuristic
        admissible (optimal path); values > 1 give a faster, possibly
        sub-optimal weighted A*.
    safety_margin_cells:
        Width, in cells, of the band of water next to land whose cost is
        multiplied by ``proximity_penalty``.
    proximity_penalty:
        Extra multiplicative penalty applied to a cell adjacent to land.

    各字段：网格分辨率（度）、单元数上限、边界余量（度）、是否允许对角移动、
    A* 启发函数权重、近岸安全带宽度（单元数）与近岸惩罚系数。
    """

    grid_resolution_deg: float = 0.25      # cell size, degrees 网格分辨率（度）
    max_grid_cells: int = 400_000          # cell budget before coarsening 单元数上限
    margin_deg: float = 2.0                # bbox margin, degrees 边界余量（度）
    diagonal_moves: bool = True            # 8-neighbour moves 八邻域移动
    heuristic_weight: float = 1.0          # 1.0 = admissible A* 启发权重
    safety_margin_cells: int = 1           # width of the near-land band, cells 近岸安全带宽度
    #: Extra multiplicative penalty applied to a cell adjacent to land.
    #: Water cells in the safety band cost 1.6x their zone cost (capped below
    #: IMPASSABLE_COST), which keeps routes one cell off the shore when possible.
    #: 近岸惩罚系数：安全带内的水域单元代价乘以 1.6。
    proximity_penalty: float = 1.6


#: Default routing configuration. 默认航线规划配置。
ROUTING = RoutingConfig()


@dataclass(frozen=True)
class GeneticConfig:
    """Parameters of the genetic-algorithm route search.

    A chromosome is a list of intermediate waypoints (lattice cells); the route
    is the chain of straight lattice lines start -> w1 -> ... -> wk -> goal.
    See :mod:`maritime_route.routing.genetic` for the operators.
    遗传算法参数：染色体为中间航点序列，航线由相邻航点之间的直线段连接而成。
    """

    population_size: int = 80          # individuals per generation 种群规模
    generations: int = 300             # upper limit of generations 最大代数
    stagnation_limit: int = 60         # stop after this many generations without improvement
    tournament_size: int = 3           # tournament selection 锦标赛规模
    crossover_rate: float = 0.9        # probability of one-point crossover 交叉概率
    mutation_rate: float = 0.35        # probability that a child is mutated 变异概率
    elite: int = 2                     # best individuals copied unchanged 精英保留数
    max_waypoints: int = 14            # longest chromosome allowed 最大航点数
    initial_waypoints: Tuple[int, int] = (1, 6)   # length range of random chromosomes
    land_penalty_weight: float = 200.0  # weight of an impassable cell in the fitness
    random_seed: int = 42              # reproducible runs 随机种子
    # stagnation_limit: 连续多少代无改进即停止。
    # initial_waypoints: 随机初始染色体的航点数范围 (最少, 最多)。
    # land_penalty_weight: 适应度中每个陆地单元的惩罚权重（以有限值代替无穷大，
    #   使穿越陆地的个体仍可比较并逐步被修复）。


#: Default genetic-algorithm configuration. 默认遗传算法配置。
GENETIC = GeneticConfig()

