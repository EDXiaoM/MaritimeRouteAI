# The four zones are ordinal around sea level (deep water -> shallow water ->
# shore -> inland), so they are encoded with a DIVERGING hypsometric scheme:
# two hues (water blue / land ochre) whose lightness is monotone within each
# pole and whose neutral midpoint is the coastline itself. This is the standard
# cartographic depth/height tint and, unlike a categorical palette, it also
# conveys the ordering of the classes.
# 四个区域沿海平面呈有序分布，因此采用"发散型"等深-等高配色：
# 水域蓝 / 陆地赭，海岸线为中性中点，每一极内部亮度单调变化。
#
# Separation was verified numerically (OKLab dE x100, all pairs):
#   light  - worst CVD dE 15.8 (protan), normal-vision dE 20.2
#   dark   - worst CVD dE 14.8 (protan), normal-vision dE 16.8
# Both clear the >=8 CVD and >=15 normal-vision gates. The two light tints fall
# below 3:1 contrast on white, so every figure and map carries direct labels or
# a legend - colour never encodes identity on its own.
# (CVD = colour vision deficiency; dE = perceptual colour difference.)
# （CVD 指色觉缺陷；dE 为感知色差。）

