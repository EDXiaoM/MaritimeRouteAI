#: Traversal cost multiplier per zone. Navigable zones are cheap, land is
#: effectively impassable. 通行代价权重：数值越大越不适合航行。
#: The cost of a grid step is (step length in km) x (multiplier of the cell), so
#: the value is dimensionless. Open sea is the reference (1.0). Coastal sea costs
#: 1.8, i.e. the planner accepts a detour of up to 80 % in open water to avoid a
#: stretch of coastal water (shallower, denser traffic). Land is infinite and is
#: stored as :data:`IMPASSABLE_COST` in numeric rasters.
#: 每步代价 = 步长(km) × 单元权重（无量纲）。近岸海 1.8 意味着为避开近岸水域可接受
#: 最多 80% 的远海绕行；陆地为无穷大，在数值栅格中以 IMPASSABLE_COST 表示。
ZONE_COST: Dict[str, float] = {
    "OPEN_SEA": 1.0,
    "COASTAL_SEA": 1.8,
    "NEAR_COAST": float("inf"),
    "COASTLINE": float("inf"),
}

#: Finite stand-in used when the planner is asked to allow land crossing
