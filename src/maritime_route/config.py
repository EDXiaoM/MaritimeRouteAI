@dataclass(frozen=True)
class TrainingConfig:
    """Hyper-parameters of the zone classifier. 神经网络训练超参数。

    Consumed by :func:`maritime_route.model.trainer.train_model` and by
    :func:`maritime_route.data.dataset.prepare` (split sizes and seed).
    The instance is immutable; ``scripts/train_model.py`` creates a modified
    copy with :func:`dataclasses.replace` when command-line options are given.

    Attributes
    ----------
    hidden_sizes:
        Width of each residual block of the MLP. A funnel 256 -> 128 -> 64 on
        a 28-dimensional input gives about 98 k trainable parameters
        (including the skip projections), enough capacity
        for the non-linear coastal boundaries without overfitting.
    dropout:
        Dropout probability applied after every hidden block.
    batch_size:
        Samples per optimiser step.
    epochs:
        Upper bound on the number of passes over the training set; early
        stopping normally ends training earlier.
    learning_rate:
        Initial learning rate of AdamW.
    weight_decay:
        Decoupled L2 regularisation coefficient of AdamW.
    early_stopping_patience:
        Epochs without validation-loss improvement before training stops.
    lr_scheduler_patience:
        Epochs without improvement before the learning rate is halved.
        Smaller than ``early_stopping_patience`` so that the rate is reduced
        (twice) before training is abandoned.
    label_smoothing:
        Probability mass moved from the true class to the other classes in
        the cross-entropy target.
    test_size, val_size:
        Shares of the corpus held out for testing and validation (70/15/15).
    random_seed:
        Seed of the data split, weight initialisation and batch shuffling.
    device:
        PyTorch device string; ``"cpu"`` because the model is small.

    各字段：隐藏层宽度、Dropout、批大小、最大轮数、学习率、权重衰减、早停耐心、
    学习率调度耐心、标签平滑、测试/验证集比例、随机种子与计算设备。
    """

    hidden_sizes: Tuple[int, ...] = (256, 128, 64)  # neurons per residual block 各残差块宽度
    dropout: float = 0.20                  # dropout probability 随机失活概率
    batch_size: int = 512                  # samples per mini-batch 批大小
    epochs: int = 120                      # max epochs (early stopping usually ends earlier) 最大轮数
    learning_rate: float = 1.5e-3          # initial AdamW learning rate 初始学习率
    weight_decay: float = 1.0e-4           # AdamW decoupled weight decay 权重衰减
    early_stopping_patience: int = 15      # epochs without val-loss improvement 早停耐心
    lr_scheduler_patience: int = 6         # epochs before LR is halved 学习率减半前的等待轮数
    label_smoothing: float = 0.02          # 2 % of target mass spread over other classes 标签平滑
    test_size: float = 0.15                # share of the corpus for testing 测试集比例
    val_size: float = 0.15                 # share of the corpus for validation 验证集比例
    random_seed: int = 42                  # reproducibility 随机种子
    device: str = "cpu"                    # PyTorch device 计算设备


#: Default training configuration. 默认训练配置。
TRAINING = TrainingConfig()

